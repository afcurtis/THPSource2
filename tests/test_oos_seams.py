"""Phase 4 completion target 2: native calls into out-of-scope code go through named seams."""

from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

import pytest

from tony.common import load_yaml
from tony.native_progress import load_native_progress
from tony.xref import coverage

ROOT = Path(__file__).resolve().parents[1]
FEATURES = ROOT / "build/xref/features-canonical.json"
ADDRESS = re.compile(r"0x00?([45][0-9a-fA-F]{5})\b")


def seams() -> list[dict]:
    return load_yaml("re/symbols/seams.yml")["seams"]


def native_sources() -> list[Path]:
    paths = sorted((ROOT / "src").rglob("*.cpp")) + sorted((ROOT / "src").rglob("*.hpp"))
    return [
        path
        for path in paths
        if "_test" not in path.name and "hooks" not in path.relative_to(ROOT / "src").parts and "generated" not in path.name
    ]


def out_of_scope() -> dict[int, dict]:
    if not FEATURES.is_file():
        pytest.skip("build/xref/features-canonical.json is generated by `tony xref`")
    document = json.loads(FEATURES.read_text())
    functions = document["functions"] if isinstance(document, dict) and "functions" in document else document
    return coverage.scope_map(coverage._library_functions(functions), native=set(load_native_progress()))


def test_every_scope_category_names_its_replacement():
    categories = coverage.scope_document()["categories"]
    assert categories
    for name, category in categories.items():
        assert category.get("title"), name
        assert category.get("replacement"), name


def test_every_out_of_scope_function_has_a_category_and_a_note():
    scope = out_of_scope()
    categories = coverage.scope_document()["categories"]
    assert scope
    for address, row in scope.items():
        assert row["category"] in categories, hex(address)
        assert row.get("note"), hex(address)


def test_seam_registry_rows_are_out_of_scope_functions_with_unique_names():
    scope = out_of_scope()
    categories = coverage.scope_document()["categories"]
    rows = seams()
    assert len({row["address"] for row in rows}) == len(rows)
    assert len({row["seam"] for row in rows}) == len(rows)
    for row in rows:
        address = row["address"]
        assert address in scope, f"{address:#010x} is not an out-of-scope function"
        assert row["category"] == scope[address]["category"], f"{address:#010x}"
        assert row["category"] in categories
        assert row["seam"].endswith("." + row["name"])
        for caller in row["callers"].split(", "):
            assert (ROOT / caller).is_file(), caller


def test_native_code_names_out_of_scope_functions_by_seam_never_by_raw_address():
    scope = out_of_scope()
    raw: dict[int, set[str]] = {}
    for path in native_sources():
        for line in path.read_text(errors="replace").split("\n"):
            for match in ADDRESS.finditer(line.split("//")[0]):
                address = int(match.group(1), 16)
                if address in scope:
                    raw.setdefault(address, set()).add(str(path.relative_to(ROOT)))
    assert not raw, (
        "use seam::<category>::<name> (src/runtime/seam_addresses_generated.hpp; register new ones in re/symbols/seams.yml): "
        + ", ".join(f"{address:#010x} ({min(files)})" for address, files in sorted(raw.items()))
    )


def test_seam_address_header_is_generated_from_the_registry():
    result = subprocess.run(
        [sys.executable, "scripts/generate_seam_addresses.py", "--check"], cwd=ROOT, capture_output=True, text=True, check=False
    )
    assert result.returncode == 0, result.stderr


def test_every_registered_seam_is_named_by_native_code():
    used: set[str] = set()
    for path in native_sources():
        used.update(f"{category}.{name}" for category, name in re.findall(r"\bseam::(\w+)::(\w+)", path.read_text(errors="replace")))
    unused = sorted(row["seam"] for row in seams() if row["seam"] not in used)
    assert not unused, "registered seams no native code names (stale rows?): " + ", ".join(unused)
