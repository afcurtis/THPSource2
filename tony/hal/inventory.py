@dataclasses.dataclass
class Derived:
    sites: list[list[Any]]      # [canonical, variant, function, kind, target]
    functions: list[list[Any]]  # [canonical, variant, name, unit, service, hook point, status]
    callbacks: list[list[Any]]  # [site, variant site, function, registered by, callback, variant callback]
    hook_points: list[list[Any]]  # [canonical, variant, name, service, owned count, site count]
    errors: list[str]
    notes: list[str]
    summary: dict[str, Any]


def derive(boundary: dict[str, Any] | None = None, *, force: bool = False) -> Derived:
    boundary = boundary if boundary is not None else load_boundary()
    facts, result = analyze("canonical", roots=boundary.get("roots", {}).get("canonical", []), force=force)
    errors: list[str] = []
    notes: list[str] = []
    records = {record["a"]: record for record in facts["functions"]}
    names = _symbol_names()
    thunks = {int(k, 16) for k in facts["thunks"]}

    def name_of(address: int) -> str:
        if address in names:
            return names[address][0]
        return records.get(address, {}).get("name", f"FUN_{address:08x}")

    # ---- sites (instruction-level imports are authoritative)
    sites: dict[int, list[Any]] = {}
    for site, entry, api, verb in facts["ground"]["imports"]:
        if entry in thunks:
            continue
        if "!" not in api:
            errors.append(f"{site:#x}: reference to an external symbol that is not an import slot ({api})")
            continue
        dll, export = api.split("!", 1)
        target = com.api_name(api) if export.startswith("Ordinal_") else export
        sites[site] = [site, entry, "import" if verb == "call" else "import-jump", f"{dll}!{target}"]
    for item in result.com_sites:
        if item.site in sites:
            errors.append(f"{item.site:#x}: both an import and a COM call")
        sites[item.site] = [item.site, item.function, "com", f"{item.interface}::{item.method}"]
    callbacks = [[site, function, label, target] for site, function, label, target in result.callbacks]

    # ---- completeness of indirect calls (instruction-level)
    accounted = set(sites) | {row[0] for row in result.untyped_vtable if row[4] == "thiscall"}
    accounted |= {row[0] for row in result.other_indirect} | {row[0] for row in result.not_com}
    accounted |= {int(root["site"]) for root in boundary.get("roots", {}).get("canonical", []) if "not_com" in root}
    for site, function, obj, offset, shape in result.untyped_vtable:
        if shape != "thiscall":
            errors.append(f"{site:#x} in {name_of(function)}: vtable call (+{offset:#x}) on {render(obj)[:60]} "
                          f"is not typed and not reviewed (shape {shape}); add a root to {BOUNDARY_PATH}")
    declared_sites = {int(root["site"]): root["interface"] for root in boundary.get("roots", {}).get("canonical", [])
                      if "site" in root and "interface" in root}
    canonical_image = Image.load("canonical")
    for site, function, shape in facts["ground"]["indirect"]:
        if site in accounted:
            continue
        if site in declared_sites:
            text = next((text for address, text in canonical_image.slice(site, site + 1)), "")
            offset = re.search(r"\+ 0x([0-9a-f]+)\]", text)
            interface = declared_sites[site]
            sites[site] = [site, function, "com", f"{interface}::{com.method(interface, int(offset.group(1), 16) if offset else 0)}"]
            continue
        # Code Ghidra left outside every function: classify from instructions.
        if shape is None:
            continue  # not `call [reg+off]`: a function pointer, never a COM vtable call
        register, pushed = shape
        if register == "ecx" and pushed != "ecx":
            continue  # C++ virtual: `this` in ECX
        errors.append(f"{site:#x} in {name_of(function) if function else 'no function'}: indirect call outside the "
                      f"decompiled code (vtable object {register}, last push {pushed or 'none'}); review it and "
                      f"add a root to {BOUNDARY_PATH}")
    for message in result.conflicts:
        errors.append(f"type conflict: {message}")
    evidence = {int(site): value for record in facts["functions"] for site, value in record.get("vtable", {}).items()}
    for item in result.com_sites:
        found = evidence.get(item.site)
        if found and found[0] == "ecx" and found[1] not in ("ecx",):
            errors.append(f"{item.site:#x}: typed {item.interface}::{item.method} but the instructions show a "
                          "C++ virtual call (vtable loaded from ECX)")

    # ---- ownership
    hook_points = boundary.get("hook_points", [])
    owner: dict[int, str] = {}
    service: dict[int, str] = {}
    status: dict[int, str] = {}
    hook_entries: dict[str, int] = {}
    for hook in hook_points:
        entry = int(hook["canonical"])
        hook_entries[hook["name"]] = entry
        if hook.get("service") not in SERVICES:
            errors.append(f"hook point {hook['name']}: unknown service {hook.get('service')!r}")
        if name_of(entry) != hook["name"] or names.get(entry, ("", ""))[1] != "curated":
            errors.append(f"hook point {hook['name']}: {entry:#010x} is curated as {name_of(entry)!r} "
                          f"({names.get(entry, ('', 'unnamed'))[1]})")
        for address in [entry] + [int(a) for a in hook.get("owns", [])]:
            if address in owner and owner[address] != hook["name"]:
                errors.append(f"{address:#010x} owned by both {owner[address]} and {hook['name']}")
            owner.setdefault(address, hook["name"])
            service.setdefault(address, hook["service"])
            status.setdefault(address, "hook" if address == entry else "owned")
    for group in boundary.get("groups", []):
        for address in (int(a) for a in group.get("functions", [])):
            if address in owner:
                errors.append(f"{address:#010x} is both in group {group['status']} and hook point {owner[address]}")
            owner[address] = ""
            service[address] = group.get("service", "")
            status[address] = group["status"]

    boundary_functions = {row[1] for row in sites.values()} | {row[3] for row in callbacks}
    for address in sorted(boundary_functions):
        if address == 0:
            errors.append("a boundary site is outside every function")
            continue
        if address >= CRT_START:
            owner.setdefault(address, "")
            service.setdefault(address, "runtime")
            status.setdefault(address, "runtime")
        if address not in status:
            kinds = collections.Counter(row[3] for row in sites.values() if row[1] == address)
            errors.append(f"{address:#010x} {name_of(address)} has boundary sites ({', '.join(kinds)}) but no hook "
                          f"point or group owns it")
    for address, hook_name in owner.items():
        if address not in boundary_functions and status.get(address) == "owned":
            notes.append(f"{address:#010x} {name_of(address)} is owned by {hook_name} but has no boundary site")

    errors += _check_closure(facts, records, hook_points, boundary, owner, status, name_of)

    # ---- variant addresses
    fmap = VariantMap.load()
    variant_starts = fmap.variant_starts
    variant_image: Image | None = None
    try:
        variant_image = Image.load(VARIANT)
    except InventoryError as exc:
        notes.append(f"{VARIANT}: {exc}; original-2000 site addresses not derived")
    ends = {address: int(record.get("end", address)) + 1 for address, record in records.items()}

    orphan_entries = set(facts["ground"].get("orphans", {}).values())
    code_starts = sorted(set(records) | orphan_entries)

    def function_end(function: int) -> int:
        if function in ends:
            return ends[function]
        index = bisect.bisect_right(code_starts, function)
        return code_starts[index] if index < len(code_starts) else function + 0x1000

    def variant_site(site: int, function: int) -> int | None:
        variant_function = fmap.get(function)
        if variant_image is None or variant_function is None:
            return None
        return _map_site(canonical_image, variant_image, site, function, max(function_end(function), site + 1),
                         variant_function, variant_starts)

    absent = {int(a) for item in boundary.get("variant_absent", []) for a in item.get("functions", [])}
    absent_sites = {int(a) for item in boundary.get("variant_absent", []) for a in item.get("sites", [])}
    site_rows = []
    for site, function, kind, target in sorted(sites.values()):
        mapped = variant_site(site, function)
        if mapped is None and variant_image is not None and status.get(function) != "runtime" \
                and function not in absent and site not in absent_sites:
            errors.append(f"{site:#x} {target} in {name_of(function)}: no original-2000 counterpart found")
        site_rows.append([site, mapped, function, kind, target])
    callback_rows = []
    for site, function, label, target in sorted(callbacks):
        callback_rows.append([site, variant_site(site, function), function, label, target, fmap.get(target)])

    units = _units(list(records) + sorted(orphan_entries))
    function_rows = []
    for address in sorted(boundary_functions | {a for a, s in status.items() if s in ("hook",)}):
        if address == 0:
            continue
        unit, basis = units.get(address, ("", "unattributed"))
        function_rows.append([
            address, fmap.get(address), name_of(address), unit + (" (adjacent)" if basis == "adjacent" else ""),
            service.get(address, "?"), owner.get(address, "?"), status.get(address, "?"),
        ])
    hook_rows = []
    for hook in hook_points:
        entry = int(hook["canonical"])
        owned = {entry, *(int(a) for a in hook.get("owns", []))}
        hook_rows.append([entry, fmap.get(entry), hook["name"], hook["service"], len(owned) - 1,
                          sum(1 for row in site_rows if row[2] in owned)])
        if fmap.get(entry) is None and entry not in absent:
            errors.append(f"hook point {hook['name']}: no original-2000 address in re/xref/{VARIANT}.yml")

    by_service = collections.Counter(service.get(row[2], "?") for row in site_rows)
    by_kind = collections.Counter(row[3] for row in site_rows)
    summary = {
        "sites": len(site_rows),
        "sites_by_kind": dict(sorted(by_kind.items())),
        "sites_by_service": dict(sorted(by_service.items())),
        "functions": len(function_rows),
        "functions_by_status": dict(sorted(collections.Counter(row[6] for row in function_rows).items())),
        "hook_points": len(hook_rows),
        "callbacks": len(callback_rows),
        "typed_com_sites": len(result.com_sites),
        "reviewed_cpp_virtuals": len(result.not_com),
        "thiscall_virtuals": sum(1 for row in result.untyped_vtable if row[4] == "thiscall"),
        "function_pointer_calls": len(result.other_indirect),
        "instruction_indirect_calls": len(facts["ground"]["indirect"]),
        "instruction_import_references": len(facts["ground"]["imports"]),
    }
    return Derived(site_rows, function_rows, callback_rows, hook_rows, errors, notes, summary)


def _check_closure(facts, records, hook_points, boundary, owner, status, name_of) -> list[str]:
    """Every owned function must be entered only from inside the HAL-owned set.

    Replacing all hook points must remove every path from game code to a
    boundary site: a direct call or a function-pointer reference from any
    function outside the hook points, their owned functions and the groups
    means some boundary site escapes its hook point.
    """

    errors = []
    starts = sorted(records)
    ends = {address: int(record.get("end", address)) for address, record in records.items()}
    orphans = {int(key, 16): value for key, value in facts["ground"].get("orphans", {}).items()}

    def containing(address: int) -> int:
        index = bisect.bisect_right(starts, address) - 1
        if index >= 0 and starts[index] <= address <= ends[starts[index]]:
            return starts[index]
        return orphans.get(address, 0)

    inside = set(owner)
    allowed_data = {int(item["from"]) for item in boundary.get("data_refs", [])}
    for address, state in status.items():
        if state not in ("owned",):
            continue
        record = records.get(address)
        if record is None:
            errors.append(f"{address:#010x}: owned function not found in Ghidra")
            continue
        for reference in record.get("refs", []):
            source = containing(reference)
            if source in inside or reference in allowed_data:
                continue
            where = f"{name_of(source)} ({reference:#x})" if source else f"data at {reference:#x}"
            errors.append(f"{name_of(address)} ({address:#010x}, owned by {owner[address]}) is referenced from "
                          f"{where}, outside every hook point")
    # every owned function must be reachable from its hook point
    callees: dict[int, set[int]] = collections.defaultdict(set)
    for record in facts["functions"]:
        for call in record["calls"]:
            if call[1] == "d":
                callees[record["a"]].add(int(call[2], 16))
        for reference in record.get("refs", []):
            source = containing(reference)
            if source:
                callees[source].add(record["a"])  # function-pointer stores count as edges
    for edge in boundary.get("indirect_edges", []):
        source, installer = int(edge["from"]), int(edge["refs_from"])
        callees[source] |= set(callees.get(installer, set()))
    for hook in hook_points:
        entry = int(hook["canonical"])
        seen, todo = {entry}, [entry]
        while todo:
            current = todo.pop()
            for callee in callees.get(current, ()):
                if callee not in seen:
                    seen.add(callee)
                    todo.append(callee)
        for address in (int(a) for a in hook.get("owns", [])):
            if address not in seen:
                errors.append(f"hook point {hook['name']} owns {name_of(address)} ({address:#010x}) but cannot "
                              "reach it")
    return errors


def _signatures(image: Image, rows: list[tuple[int, str]]) -> list[tuple[int, str | None]]:
    """Per-row call signatures, resolving `call reg` after `mov reg, [IAT]`."""

    cached: dict[str, str] = {}
    result = []
    for address, text in rows:
        load = re.match(r"mov (e[a-z]{2}), dword ptr \[0x([0-9a-f]+)\]$", text)
        if load:
            name = image.iat.get(int(load.group(2), 16))
            if name:
                cached[load.group(1)] = name
            else:
                cached.pop(load.group(1), None)
        elif re.match(r"(mov|lea|pop|xor) (e[a-z]{2})\b", text):
            cached.pop(text.split()[1].rstrip(","), None)
        register_call = re.fullmatch(r"call (e[a-z]{2})", text)
        if register_call and register_call.group(1) in cached:
            result.append((address, f"call:{cached[register_call.group(1)]}"))
        else:
            result.append((address, image.signature(text)))
    return result


def _map_site(canonical: Image, variant: Image, site: int, function: int, end: int, variant_start: int,
              variant_starts: list[int]) -> int | None:
    rows = _signatures(canonical, canonical.slice(function, end))
    signature = next((sig for address, sig in rows if address == site), None)
    if signature is None:
        return None
    ordinal = sum(1 for address, sig in rows if address < site and sig == signature)
    index = bisect.bisect_right(variant_starts, variant_start)
    variant_end = variant_starts[index] if index < len(variant_starts) else variant_start + (end - function) + 0x100
    matches = [address for address, sig in _signatures(variant, variant.slice(variant_start, variant_end))
               if sig == signature]
    return matches[ordinal] if ordinal < len(matches) else None


