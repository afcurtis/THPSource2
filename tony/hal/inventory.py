"""Derive, write and check the platform boundary inventory.

`re/config/hal_boundary.yml` has two parts:

- curated: `roots` (reviewed interface declarations, see tony.hal.infer),
  `hook_points` (the game-level functions a HAL service replaces and the
  boundary functions each one owns), `groups` (boundary functions that are
  deliberately not hooked: dead code, multiplayer) and `indirect_edges`
  (dispatch-table calls the call graph cannot see);
- generated (`tony hal derive --write`): every boundary site, function and
  platform callback, with canonical and original-2000 addresses.

`tony hal check` re-derives the generated part from Ghidra and fails when it
differs, when any import, COM or indirect call is unaccounted for, or when a
hook point does not fully own its functions (some unhooked game function could
still reach a boundary site without passing through a hook point).
"""

from __future__ import annotations

import bisect
import collections
import dataclasses
import functools
import re
import subprocess
from pathlib import Path
from typing import Any

import yaml

from ..common import load_yaml, resolve
from . import com
from .audit import BOUNDARY_PATH, analyze, load_boundary
from .expr import render

ZLIB = (0x004F9C80, 0x004FFD3A)  # zlib 1.1.2, statically linked (inflate/deflate strings)
CRT_START = 0x004FFD3A  # statically linked MSVC runtime (__global_unwind2, operator new, _malloc ...)
VARIANT = "original_2000"
GENERATED_MARKER = "# ---- generated by `tony hal derive --write`; do not edit below this line ----"

SERVICES = {
    "clock": "simulation timer, sleeps and tick counts",
    "window": "window, message pump, window procedure, cursor visibility",
    "input": "keyboard, mouse, joystick and force feedback (DirectInput)",
    "video": "DirectDraw/Direct3D 7 device, surfaces, textures, primitive drawing, present",
    "audio": "DirectSound buffers and WAV loading",
    "movie": "Bink video and streamed music, and their DirectDraw/Direct3D output",
    "fs": "file system: CD detection and check, path resolution, file search, settings",
    "net": "multiplayer (DirectPlay, lobby, setup dialogs): out of scope, stays retail",
    "debug": "diagnostics (log output, screenshots): not a HAL service",
    "runtime": "statically linked MSVC runtime: replaced by the host C runtime in a standalone build",
}
STATUSES = ("hook", "owned", "dead", "out_of_scope", "runtime")


class InventoryError(RuntimeError):
    pass


