@dataclasses.dataclass
class Image:
    """One executable: bytes, import slots, and a flat disassembly of .text."""

    path: Path
    image: Any
    iat: dict[int, str]
    rows: list[tuple[int, str]]
    starts: list[int]

    @classmethod
    def load(cls, build: str) -> Image:
        import pefile

        from ..hooks import PeImage, build_executable

        path = build_executable(build)
        if path is None or not path.is_file():
            raise InventoryError(f"{build}: executable not present")
        pe = pefile.PE(str(path), fast_load=True)
        pe.parse_data_directories(directories=[pefile.DIRECTORY_ENTRY["IMAGE_DIRECTORY_ENTRY_IMPORT"]])
        iat: dict[int, str] = {}
        for entry in getattr(pe, "DIRECTORY_ENTRY_IMPORT", []):
            dll = entry.dll.decode().upper()
            for item in entry.imports:
                name = item.name.decode() if item.name else f"Ordinal_{item.ordinal}"
                iat[int(item.address)] = f"{dll}!{name}"
        rows = _disassemble_text(path, pe)
        return cls(path, PeImage(path), iat, rows, [row[0] for row in rows])

    def slice(self, start: int, stop: int) -> list[tuple[int, str]]:
        low = bisect.bisect_left(self.starts, start)
        high = bisect.bisect_left(self.starts, stop)
        return self.rows[low:high]

    def signature(self, text: str) -> str | None:
        """Identity of a call/jump used to pair sites across builds."""

        match = re.match(r"(call|jmp)\s+(.*)$", text)
        if not match:
            return None
        verb, operand = match.groups()
        absolute = re.fullmatch(r"dword ptr \[0x([0-9a-f]+)\]", operand)
        if absolute:
            name = self.iat.get(int(absolute.group(1), 16))
            return f"{verb}:{name}" if name else None
        direct = re.fullmatch(r"0x([0-9a-f]+)(?: <.*>)?", operand)
        if direct and verb == "call":
            target = int(direct.group(1), 16)
            try:
                code = self.image.read(target, 6)
            except Exception:  # noqa: BLE001 - outside the image
                return "call:direct"
            if code[:2] == b"\xff\x25":
                name = self.iat.get(int.from_bytes(code[2:6], "little"))
                if name:
                    return f"call:{name}"
            return "call:direct"
        vcall = re.fullmatch(r"dword ptr \[e[a-z]{2}(?: \+ 0x([0-9a-f]+))?\]", operand)
        if vcall and verb == "call":
            return f"vcall:{int(vcall.group(1) or '0', 16):#x}"
        return f"{verb}:other"


def _disassemble_text(path: Path, pe) -> list[tuple[int, str]]:
    from ..hooks import _objdump

    tool = _objdump()
    if tool is None:
        raise InventoryError("llvm-objdump not found")
    base = pe.OPTIONAL_HEADER.ImageBase
    text = next(section for section in pe.sections if section.Name.rstrip(b"\0") == b".text")
    start = base + text.VirtualAddress
    stop = start + max(text.Misc_VirtualSize, text.SizeOfRawData)
    output = subprocess.run(
        [tool, "-d", "--no-show-raw-insn", "-M", "intel", f"--start-address={start:#x}",
         f"--stop-address={stop:#x}", str(path)],
        text=True, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, check=False,
    ).stdout
    rows = []
    for line in output.splitlines():
        match = re.match(r"^\s*([0-9a-f]+):\s+(.*?)\s*$", line)
        if match:
            rows.append((int(match.group(1), 16), re.sub(r"\s+", " ", match.group(2))))
    return rows


