@functools.lru_cache(maxsize=1)
def _symbol_names() -> dict[int, tuple[str, str]]:
    """address -> (name, 'curated'|'imported')."""

    names: dict[int, tuple[str, str]] = {}
    for item in load_yaml("re/symbols/imported.yml").get("functions", []):
        names[int(item["address"])] = (item["name"], "imported")
    for item in load_yaml("re/symbols/functions.yml").get("functions", []):
        names[int(item["address"])] = (item["name"], "curated")
    return names


@dataclasses.dataclass
class VariantMap:
    """canonical function start -> original-2000 function start.

    `re/xref/original_2000.yml` maps most functions. Two fallbacks cover the
    rest: function starts that appear in its data map (function pointers in
    tables, e.g. the primitive dispatch table), and link order: between two
    mapped neighbours whose spacing is identical in both builds, a canonical
    address maps by the same offset. Every site mapped this way is still
    verified by instruction-signature matching.
    """

    functions: dict[int, int]
    data: dict[int, int]
    canonical_marks: list[int]
    variant_starts: list[int]

    @classmethod
    def load(cls) -> VariantMap:
        document = load_yaml(f"re/xref/{VARIANT}.yml")
        functions = {int(row[1]): int(row[0]) for row in document.get("functions", [])}
        data = {int(row[1]): int(row[0]) for row in document.get("data", [])}
        starts = sorted({*functions.values(), *(int(row[0]) for row in document.get("unmatched_variant", []))})
        return cls(functions, data, sorted(functions), starts)

    def get(self, address: int | None) -> int | None:
        if address is None:
            return None
        if address in self.functions:
            return self.functions[address]
        if address in self.data:
            return self.data[address]
        index = bisect.bisect_right(self.canonical_marks, address)
        if 0 < index < len(self.canonical_marks):
            before, after = self.canonical_marks[index - 1], self.canonical_marks[index]
            variant_before, variant_after = self.functions[before], self.functions[after]
            if after - before == variant_after - variant_before:
                return variant_before + (address - before)
        return None


def _units(functions: list[int]) -> dict[int, tuple[str, str]]:
    """address -> (unit, basis). Attribution comes from `tony xref units`;
    unattributed functions between two functions of the same unit inherit it
    (VC6 emits one object file's functions contiguously)."""

    attributed = {int(a): unit for a, unit, _basis in load_yaml("re/xref/source-units.yml").get("functions", [])}
    ordered = sorted(functions)
    result: dict[int, tuple[str, str]] = {}
    marks = [address for address in ordered if address in attributed]
    for address in ordered:
        if ZLIB[0] <= address < ZLIB[1]:
            result[address] = ("zlib 1.1.2 (static)", "library")
        elif address >= CRT_START:
            result[address] = ("MSVC runtime (static)", "library")
        elif address in attributed:
            result[address] = (attributed[address], "assert")
        else:
            index = bisect.bisect_left(marks, address)
            before = attributed[marks[index - 1]] if index > 0 else None
            after = attributed[marks[index]] if index < len(marks) else None
            if before is not None and before == after:
                result[address] = (before, "adjacent")
            elif before is not None and after is not None:
                # link order brackets the function between two units
                result[address] = (f"{before} .. {after}", "between")
            else:
                result[address] = ("", "unattributed")
    return result


