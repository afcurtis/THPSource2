def _row(cells: list[Any]) -> str:
    out = []
    for cell in cells:
        if cell is None:
            out.append("null")
        elif isinstance(cell, int) and cell >= 0x400000:
            out.append(f"0x{cell:08x}")
        elif isinstance(cell, int):
            out.append(str(cell))
        else:
            out.append(yaml.safe_dump(str(cell), default_style='"').strip())
    return "  - [" + ", ".join(out) + "]"


def render_generated(derived: Derived) -> str:
    lines = [GENERATED_MARKER, "generated:"]
    summary = yaml.safe_dump({"summary": derived.summary}, sort_keys=False, default_flow_style=False).rstrip()
    lines += ["  " + line for line in summary.splitlines()]
    sections = (
        ("hook_points", "[canonical, original_2000, name, service, owned functions, sites]", derived.hook_points),
        ("functions", "[canonical, original_2000, name, unit, service, hook point, status]", derived.functions),
        ("callbacks", "[site, original_2000 site, function, registered by, callback, original_2000 callback]",
         derived.callbacks),
        ("sites", "[canonical, original_2000, function, kind, target]", derived.sites),
    )
    for key, columns, rows in sections:
        lines.append(f"  # {key}: {columns}")
        lines.append(f"  {key}:" + ("" if rows else " []"))
        lines += ["  " + _row(row) for row in rows]
    return "\n".join(lines) + "\n"


def split_document(text: str) -> tuple[str, str]:
    if GENERATED_MARKER in text:
        head, _, tail = text.partition(GENERATED_MARKER)
        return head.rstrip() + "\n", GENERATED_MARKER + tail
    return text.rstrip() + "\n", ""


def write(derived: Derived, path: str | Path = BOUNDARY_PATH) -> Path:
    target = resolve(path)
    head, _old = split_document(target.read_text(encoding="utf-8"))
    target.write_text(head + "\n" + render_generated(derived), encoding="utf-8")
    return target


def check(path: str | Path = BOUNDARY_PATH, *, force: bool = False) -> tuple[list[str], list[str], Derived]:
    target = resolve(path)
    text = target.read_text(encoding="utf-8")
    boundary = yaml.safe_load(text) or {}
    derived = derive(boundary, force=force)
    errors = list(derived.errors)
    _head, generated = split_document(text)
    if generated != render_generated(derived):
        errors.append(f"{BOUNDARY_PATH}: generated inventory is stale; run `tony hal derive --write`")
    return errors, derived.notes, derived
