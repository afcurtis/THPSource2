#!/usr/bin/env python3
"""Generate src/runtime/create_tables.cpp from the canonical executable.

Usage: python scripts/generate_create_tables.py [--check]

The create-a-skater code reads static tables the executable ships in .data, at their retail addresses
(RetailMemory regions):

  * 0x00525c00..0x00526000: the colour preset rows (hue, saturation, value; 12 bytes each), the four
    lists of body part name pointers (head, upper body, lower body, board), the bitmap hue table
    (name pointer, hue pairs) and the part name and bitmap name strings they point at;
  * 0x00539df8..0x00539e20: the two rows of ten stat offsets the first two builds add, and the three
    pointers (0x00539e10) that name those rows and a third, runtime, row at 0x0056db50 (all zero);
  * 0x0055fe10: the empty string that ends the bitmap hue table.

`--check` exits non-zero when the checked-in file differs from what the executable produces.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pefile

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from tony.hooks import _canonical_exe  # noqa: E402

OUTPUT = ROOT / "src" / "runtime" / "create_tables.cpp"

# (virtual address, size)
REGIONS = [
    (0x00525C00, 0x400),
    (0x00539DF8, 0x28),
    (0x0055FE10, 0x10),
]


def c_bytes(data: bytes, per_line: int = 16) -> list[str]:
    return ["    " + ", ".join(f"0x{b:02x}" for b in data[i : i + per_line]) + "," for i in range(0, len(data), per_line)]


def render() -> str:
    pe = pefile.PE(str(_canonical_exe()))
    base = pe.OPTIONAL_HEADER.ImageBase
    lines = [
        '#include "create_tables.hpp"',
        "",
        "// Generated by scripts/generate_create_tables.py from the canonical PC executable.",
        "// Do not edit; rerun the script.",
        "namespace opentony::runtime {",
        "namespace {",
        "",
    ]
    for index, (va, size) in enumerate(REGIONS):
        data = pe.get_data(va - base, size)
        lines.append(f"// VA {va:#010x}, {len(data):#x} bytes")
        lines.append(f"constexpr std::uint8_t kRegion{index}[{len(data)}] = {{")
        lines += c_bytes(data)
        lines.append("};")
        lines.append("")
    lines += [
        "constexpr StaticRegion kRegions[] = {",
        *[f"    {{0x{va:08x}, kRegion{i}}}," for i, (va, _) in enumerate(REGIONS)],
        "};",
        "",
        "}  // namespace",
        "",
        "std::span<const StaticRegion> create_static_regions() noexcept { return kRegions; }",
        "",
        "}  // namespace opentony::runtime",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = open(OUTPUT, newline="").read() if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT} is stale; rerun scripts/generate_create_tables.py", file=sys.stderr)
            return 1
        return 0
    with open(OUTPUT, "w", newline="") as handle:
        handle.write(text)
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
