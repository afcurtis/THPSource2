#!/usr/bin/env python3
"""Generate src/runtime/seam_addresses_generated.hpp from re/symbols/seams.yml.

Usage: python scripts/generate_seam_addresses.py [--check]

Native code names an out-of-scope retail function by its seam (`seam::hal::D3D_ClearBuffers`),
never by a raw address; this header is the one place the address appears. The retail-hosted
build passes the constant to `engine(...)`; the standalone (5.5) resolves each `seam::kSeams`
row to the replacement of its category instead. `tests/test_oos_seams.py` forbids raw
out-of-scope addresses everywhere else in native code.
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SEAMS = ROOT / "re/symbols/seams.yml"
OUTPUT = ROOT / "src/runtime/seam_addresses_generated.hpp"


def generate() -> str:
    rows = yaml.safe_load(SEAMS.read_text())["seams"]
    categories: dict[str, list[dict]] = {}
    for row in rows:
        prefix, _, name = row["seam"].partition(".")
        if name != row["name"]:
            raise ValueError(f"{row['seam']}: seam id does not end in the function name {row['name']}")
        categories.setdefault(prefix, []).append(row)
    lines = [
        "// Generated by scripts/generate_seam_addresses.py from re/symbols/seams.yml; do not edit.",
        "//",
        "// The out-of-scope retail functions native code calls (re/symbols/scope.yml), by seam. A raw",
        "// address anywhere else in native code fails tests/test_oos_seams.py. The retail-hosted build",
        "// passes these constants to `engine(...)`; the standalone resolves `kSeams` to the replacement",
        "// of the category instead.",
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace opentony::seam {",
    ]
    for prefix in sorted(categories):
        lines += ["", f"namespace {prefix} {{"]
        for row in sorted(categories[prefix], key=lambda r: r["address"]):
            lines.append(f"inline constexpr std::uint32_t {row['name']} = 0x{row['address']:08x};")
        lines.append(f"}}  // namespace {prefix}")
    lines += [
        "",
        "struct SeamEntry {",
        "    const char* id;",
        "    const char* category;",
        "    std::uint32_t address;",
        "};",
        "",
        "inline constexpr SeamEntry kSeams[] = {",
    ]
    for row in sorted(rows, key=lambda r: r["address"]):
        lines.append(f'    {{"{row["seam"]}", "{row["category"]}", 0x{row["address"]:08x}}},')
    lines += [
        "};",
        "inline constexpr std::size_t kSeamCount = sizeof(kSeams) / sizeof(kSeams[0]);",
        "",
        "}  // namespace opentony::seam",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    text = generate()
    if "--check" in argv:
        if not OUTPUT.is_file() or OUTPUT.read_text() != text:
            print(f"{OUTPUT.relative_to(ROOT)} is stale: run python scripts/generate_seam_addresses.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
