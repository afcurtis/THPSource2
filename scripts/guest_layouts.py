#!/usr/bin/env python3
"""Generate src/runtime/guest_layouts_generated.hpp from re/types (milestone 11a, docs/PORT64_AUDIT.md D4).

For every `fixed_layout` type the header has, in namespace opentony::runtime::guest:

* `k<Type>Size` (when the type declares a size) and `k<Type>_<field>` offsets for every field;
* a packed mirror struct `<Type>Mirror` (explicit-width fields, `GuestPtr<T>` for pointers, byte padding for gaps) and
  `static_assert`s that its size and every field offset equal the corpus. A type with overlay groups, or a field of unknown size, gets
  constants and the asserts the corpus allows (`offset + size <= type size`) but no mirror.

The mirrors are for the asserts only. The Kits use the constants and, from 11c, the views of `guest_views_generated.hpp` (`generate_views`):
one handle class `<Type>View(RetailMemory&, address)` per fixed layout with a getter, a setter and an `_address` accessor per field
(`GuestPtr<T>` for pointers, an index argument for arrays, a nested view for an embedded layout).

    python scripts/guest_layouts.py            # rewrite the header
    python scripts/guest_layouts.py --check    # exit 1 if the committed header is stale
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from tony.recovered_types import (  # noqa: E402
    PRIMITIVE_SIZES,
    TypeExpression,
    _expression_size,
    load_type_definitions,
    parse_type_expression,
)

OUTPUT = ROOT / "src/runtime/guest_layouts_generated.hpp"
VIEWS_OUTPUT = ROOT / "src/runtime/guest_views_generated.hpp"
DOCUMENT = ROOT / "docs/PORT64_AUDIT.md"
INVENTORY_BEGIN = "<!-- inventory:begin (scripts/guest_layouts.py --inventory writes this block) -->"
INVENTORY_END = "<!-- inventory:end -->"
NEWLINE = chr(10)
CRLF = chr(13) + chr(10)
POINTER_SIZE = 4  # guest pointers are 32-bit retail addresses (D1)
SCALAR = {
    "i8": "std::int8_t",
    "u8": "std::uint8_t",
    "char": "char",
    "i16": "std::int16_t",
    "u16": "std::uint16_t",
    "i32": "std::int32_t",
    "u32": "std::uint32_t",
    "f32": "float",
    "q12_i32": "std::int32_t",
    "q16_i32": "std::int32_t",
    "i64": "std::int64_t",
    "u64": "std::uint64_t",
    "f64": "double",
}


def identifier(text: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", text)


def assign_ids(fields: list[dict]) -> None:
    """Gives every field its `_id`: the identifier of its name, or `<name>_at_<offset>` for the second field of that name."""
    seen: set[str] = set()
    for field in fields:
        fid = identifier(str(field["name"]))
        if fid in seen:
            fid = f"{fid}_at_{int(field['offset']):x}"
        seen.add(fid)
        field["_id"] = fid


def element_cpp(expression: TypeExpression) -> str | None:
    """C++ spelling of an element type, or None when it has no fixed spelling."""
    if expression.kind == "primitive":
        return SCALAR.get(expression.name or "")
    if expression.kind == "pointer":
        pointee = expression.element
        inner = element_cpp(pointee) if pointee is not None and pointee.kind != "named" else None
        if pointee is not None and pointee.kind == "named":
            inner = "void"  # a named pointee is a view type from 11c; the layout only needs the width
        return f"GuestPtr<{inner or 'void'}>"
    return None


def member_declaration(name: str, expression: TypeExpression, size: int) -> str:
    if expression.kind == "array":
        element = element_cpp(expression.element) if expression.element is not None else None
        if element is not None:
            return f"{element} {name}[{expression.count}];"
    elif element_cpp(expression) is not None:
        return f"{element_cpp(expression)} {name};"
    return f"std::uint8_t {name}[{size}];"


def generate() -> str:
    definitions = load_type_definitions()
    sizes = {name: definition.get("size") for name, definition in definitions.items()}
    out: list[str] = [
        "// GENERATED by scripts/guest_layouts.py from re/types. Do not edit; run the script (pytest fails when this file is stale).",
        "// Offsets and sizes of the recovered retail layouts (32-bit guest addresses, docs/PORT64_AUDIT.md D1/D4), asserted at compile time",
        "// in the 32-bit and the 64-bit builds.",
        "#pragma once",
        "",
        '#include "guest_ptr.hpp"',
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace opentony::runtime::guest {",
        "",
    ]
    mirrored = constants_only = 0
    for name, definition in definitions.items():
        if definition["kind"] != "fixed_layout":
            continue
        tid = identifier(name)
        size = definition.get("size")
        fields = sorted(definition.get("fields") or [], key=lambda field: int(field["offset"]))
        out.append(f"// {name} ({definition.get('confidence')}){'' if size is not None else ', size not recovered'}")
        if size is not None:
            out.append(f"inline constexpr std::size_t k{tid}Size = {size};")
        assign_ids(fields)
        for field in fields:
            out.append(f"inline constexpr std::size_t k{tid}_{field['_id']} = 0x{int(field['offset']):x};")
        # field sizes, for bounds and the mirror
        measured = []
        for field in fields:
            expression = parse_type_expression(field["type"])
            measured.append((field, expression, _expression_size(expression, sizes, POINTER_SIZE)))
        overlays = any(field.get("overlay_group") for field in fields)
        unknown = any(width is None for _field, _expression, width in measured)
        if size is not None:
            for field, _expression, width in measured:
                if width is not None:
                    out.append(
                        f"static_assert(k{tid}_{field['_id']} + {width} <= k{tid}Size, \"{name}.{field['name']} lies inside the type\");"
                    )
        if overlays or unknown or not fields:
            constants_only += 1
            out.append("")
            continue
        mirrored += 1
        out.append("#pragma pack(push, 1)")
        out.append(f"struct {tid}Mirror {{")
        cursor = 0
        for field, expression, width in measured:
            offset = int(field["offset"])
            if offset > cursor:
                out.append(f"    std::uint8_t pad_{cursor:x}[{offset - cursor}];")
            out.append(f"    {member_declaration(field['_id'], expression, width)}")
            cursor = offset + width
        if size is not None and cursor < size:
            out.append(f"    std::uint8_t pad_{cursor:x}[{size - cursor}];")
        out.append("};")
        out.append("#pragma pack(pop)")
        if size is not None:
            out.append(f"static_assert(sizeof({tid}Mirror) == k{tid}Size, \"{name} size\");")
        for field, _expression, _width in measured:
            out.append(
                f"static_assert(offsetof({tid}Mirror, {field['_id']}) == k{tid}_{field['_id']}, \"{name}.{field['name']} offset\");"
            )
        out.append("")
    out.append(f"// {mirrored} layouts mirrored, {constants_only} with constants and bounds only (overlays, unsized fields, or no fields).")
    out.append("")
    out.append("}  // namespace opentony::runtime::guest")
    out.append("")
    return "\n".join(out)


CPP_KEYWORDS = {
    "alignas", "alignof", "and", "asm", "auto", "bool", "break", "case", "catch", "char", "class", "const", "constexpr", "continue",
    "decltype", "default", "delete", "do", "double", "else", "enum", "explicit", "export", "extern", "false", "float", "for", "friend",
    "goto", "if", "inline", "int", "long", "mutable", "namespace", "new", "noexcept", "not", "nullptr", "operator", "or", "private",
    "protected", "public", "register", "return", "short", "signed", "sizeof", "static", "struct", "switch", "template", "this", "throw",
    "true", "try", "typedef", "typeid", "typename", "union", "unsigned", "using", "virtual", "void", "volatile", "while", "xor",
}
RESERVED_MEMBERS = {"address", "memory"}


def member_name(fid: str) -> str:
    """A C++ member name for a field id: no leading digit, no keyword, none of the view's own members."""
    if fid[0].isdigit():
        fid = f"f_{fid}"
    if fid in CPP_KEYWORDS or fid in RESERVED_MEMBERS:
        fid += "_"
    return fid


def view_scalar(expression: TypeExpression) -> str | None:
    if expression.kind == "primitive":
        return SCALAR.get(expression.name or "")
    return None


def view_pointer(expression: TypeExpression) -> str | None:
    """`GuestPtr<...>` with a named pointee kept as its tag (a forward-declared struct)."""
    if expression.kind != "pointer" or expression.element is None:
        return None
    pointee = expression.element
    if pointee.kind == "named":
        return f"GuestPtr<{identifier(pointee.name or 'void')}>"
    inner = view_scalar(pointee) or view_pointer(pointee)
    return f"GuestPtr<{inner or 'void'}>"


def generate_views() -> str:
    """The view classes: one per fixed layout, with a getter / setter / address accessor for every field the corpus gives a width."""
    definitions = load_type_definitions()
    sizes = {name: definition.get("size") for name, definition in definitions.items()}

    def resolve(name: str) -> str:
        while definitions.get(name, {}).get("kind") == "alias":
            name = str(definitions[name]["target"])
        return name

    fixed = {name for name, definition in definitions.items() if definition["kind"] == "fixed_layout" and name == resolve(name)}
    out: list[str] = [
        "// GENERATED by scripts/guest_layouts.py from re/types. Do not edit; run the script (pytest fails when this file is stale).",
        "// Typed views over game memory (docs/PORT64_AUDIT.md D4): one handle class per recovered fixed layout, reading and writing its fields",
        "// at the offsets asserted in guest_layouts_generated.hpp through `RetailMemory`, on the 32-bit and the 64-bit builds alike.",
        "#pragma once",
        "",
        '#include "guest_layouts_generated.hpp"',
        '#include "guest_view.hpp"',
        "",
        "namespace opentony::runtime::guest {",
        "",
        "// pointee tags: `GuestPtr<Name>` points at a `Name`; `NameView` is the handle that reads it",
    ]
    for name in sorted(definitions):
        out.append(f"struct {identifier(name)};")
    out.append("")
    for name in sorted(fixed):
        out.append(f"class {identifier(name)}View;")
    out.append("")
    deferred: list[str] = []
    views = 0
    accessors = 0
    for name in sorted(fixed):
        definition = definitions[name]
        tid = identifier(name)
        fields = sorted(definition.get("fields") or [], key=lambda field: int(field["offset"]))
        assign_ids(fields)
        size = definition.get("size")
        taken: set[str] = set(RESERVED_MEMBERS)
        body: list[str] = []

        def claim(*names: str) -> None:
            for member in names:
                if member in taken:
                    raise SystemExit(f"{name}: view member {member} is declared twice")
                taken.add(member)

        for field in fields:
            fid = field["_id"]
            member = member_name(fid)
            offset = f"k{tid}_{fid}"
            expression = parse_type_expression(field["type"])
            scalar = view_scalar(expression)
            pointer = view_pointer(expression)
            element = expression.element if expression.kind == "array" else None
            element_scalar = view_scalar(element) if element is not None else None
            element_pointer = view_pointer(element) if element is not None else None
            element_named = resolve(element.name or "") if element is not None and element.kind == "named" else None
            named = resolve(expression.name or "") if expression.kind == "named" else None
            claim(member + "_address")
            if scalar is not None or pointer is not None:
                cpp = scalar or pointer
                claim(member, "set_" + member)
                body.append(f"    [[nodiscard]] std::uint32_t {member}_address() const noexcept {{ return address_ + {offset}; }}")
                if pointer is not None:
                    body.append(f"    [[nodiscard]] {cpp} {member}() const {{ return {cpp}{{memory_->u32(address_ + {offset})}}; }}")
                    body.append(f"    void set_{member}({cpp} value) const {{ memory_->set32(address_ + {offset}, value.address); }}")
                else:
                    body.append(f"    [[nodiscard]] {cpp} {member}() const {{ return detail::load<{cpp}>(*memory_, address_ + {offset}); }}")
                    body.append(f"    void set_{member}({cpp} value) const {{ detail::store<{cpp}>(*memory_, address_ + {offset}, value); }}")
                accessors += 1
            elif element is not None and (element_scalar is not None or element_pointer is not None):
                cpp = element_scalar or element_pointer
                width = _expression_size(element, sizes, POINTER_SIZE)
                count = expression.count
                claim(member, "set_" + member, member + "_count")
                body.append(f"    static constexpr std::size_t {member}_count = {count};")
                body.append(
                    f"    [[nodiscard]] std::uint32_t {member}_address(std::size_t index = 0) const {{ return address_ + {offset} + static_cast<std::uint32_t>(index * {width}); }}"
                )
                check = f'if (index >= {member}_count) detail::index_fault("{name}.{field["name"]}", index, {member}_count);'
                if element_pointer is not None:
                    body.append(f"    [[nodiscard]] {cpp} {member}(std::size_t index) const {{ {check} return {cpp}{{memory_->u32({member}_address(index))}}; }}")
                    body.append(f"    void set_{member}(std::size_t index, {cpp} value) const {{ {check} memory_->set32({member}_address(index), value.address); }}")
                else:
                    body.append(f"    [[nodiscard]] {cpp} {member}(std::size_t index) const {{ {check} return detail::load<{cpp}>(*memory_, {member}_address(index)); }}")
                    body.append(f"    void set_{member}(std::size_t index, {cpp} value) const {{ {check} detail::store<{cpp}>(*memory_, {member}_address(index), value); }}")
                accessors += 1
            elif named is not None and named in fixed:
                claim(member)
                body.append(f"    [[nodiscard]] std::uint32_t {member}_address() const noexcept {{ return address_ + {offset}; }}")
                body.append(f"    [[nodiscard]] {identifier(named)}View {member}() const;")
                deferred.append(
                    f"inline {identifier(named)}View {tid}View::{member}() const {{ return {identifier(named)}View(*memory_, address_ + {offset}); }}"
                )
                accessors += 1
            elif element_named is not None and element_named in fixed and sizes.get(element_named) is not None:
                width = sizes[element_named]
                claim(member, member + "_count")
                body.append(f"    static constexpr std::size_t {member}_count = {expression.count};")
                body.append(
                    f"    [[nodiscard]] std::uint32_t {member}_address(std::size_t index = 0) const {{ return address_ + {offset} + static_cast<std::uint32_t>(index * {width}); }}"
                )
                body.append(f"    [[nodiscard]] {identifier(element_named)}View {member}(std::size_t index) const;")
                check = f'if (index >= {member}_count) detail::index_fault("{name}.{field["name"]}", index, {member}_count);'
                deferred.append(
                    f"inline {identifier(element_named)}View {tid}View::{member}(std::size_t index) const {{ {check} return {identifier(element_named)}View(*memory_, {member}_address(index)); }}"
                )
                accessors += 1
            else:
                body.append(f"    [[nodiscard]] std::uint32_t {member}_address() const noexcept {{ return address_ + {offset}; }}")
        out.append(f"// {name} ({definition.get('confidence')})")
        out.append(f"class {tid}View final {{")
        out.append("public:")
        if size is not None:
            out.append(f"    static constexpr std::size_t kSize = k{tid}Size;")
        out.append(f"    constexpr {tid}View(RetailMemory& memory, std::uint32_t address) noexcept : memory_(&memory), address_(address) {{}}")
        out.append("    [[nodiscard]] constexpr std::uint32_t address() const noexcept { return address_; }")
        out.append("    [[nodiscard]] RetailMemory& memory() const noexcept { return *memory_; }")
        out.extend(body)
        out.append("")
        out.append("private:")
        out.append("    RetailMemory* memory_;")
        out.append("    std::uint32_t address_;")
        out.append("};")
        out.append("")
        views += 1
    out.extend(deferred)
    out.append("")
    out.append(f"// {views} views, {accessors} typed field groups.")
    out.append("")
    out.append("}  // namespace opentony::runtime::guest")
    out.append("")
    return "\n".join(out)


def type_files() -> dict[str, str]:
    """Type name -> the file of re/types that defines it."""
    import yaml

    owners: dict[str, str] = {}
    for path in sorted((ROOT / "re/types").glob("*.yml")):
        for definition in yaml.safe_load(path.read_text(encoding="utf-8")).get("types", []):
            owners[str(definition["name"])] = path.name
    return owners


def inventory() -> str:
    """The audit's inventory table: one row per type, from the corpus."""
    definitions = load_type_definitions()
    rows = [
        "| Type | File | Kind | Size | Fields | Pointers | Asserted |",
        "|---|---|---|---|---|---|---|",
    ]
    for name, definition in definitions.items():
        source = type_files()[name]
        if definition["kind"] == "alias":
            rows.append(f"| {name} | {source} | alias of {definition['target']} | | | | |")
            continue
        fields = definition.get("fields") or []
        pointers = sum(1 for field in fields if "pointer<" in str(field["type"]))
        size = definition.get("size")
        if definition["kind"] != "fixed_layout":
            asserted = "no (variable record)"
        else:
            asserted = "mirror" if f"struct {identifier(name)}Mirror" in generate_cache() else "constants and bounds"
        rows.append(
            f"| {name} | {source} | {definition['kind']} | {size if size is not None else 'unrecovered'} | {len(fields)} | {pointers} | {asserted} |"
        )
    return NEWLINE.join(rows)


_generated: list[str] = []


def generate_cache() -> str:
    if not _generated:
        _generated.append(generate())
    return _generated[0]


def with_inventory(document: str) -> str:
    start = document.index(INVENTORY_BEGIN) + len(INVENTORY_BEGIN)
    return document[:start] + NEWLINE * 2 + inventory() + NEWLINE * 2 + document[document.index(INVENTORY_END) :]


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if the committed header differs from the generated one")
    parser.add_argument("--inventory", action="store_true", help="rewrite the inventory table in docs/PORT64_AUDIT.md")
    args = parser.parse_args()
    if args.inventory:
        DOCUMENT.write_text(with_inventory(DOCUMENT.read_text(encoding="utf-8").replace(CRLF, NEWLINE)), encoding="utf-8", newline=NEWLINE)
        print(f"wrote the inventory in {DOCUMENT.relative_to(ROOT)}")
        return 0
    outputs = ((OUTPUT, generate()), (VIEWS_OUTPUT, generate_views()))
    if args.check:
        stale = False
        for path, text in outputs:
            current = path.read_text(encoding="utf-8") if path.exists() else ""
            if current.replace("\r\n", "\n") != text:
                print(f"{path.relative_to(ROOT)} is stale: run python scripts/guest_layouts.py", file=sys.stderr)
                stale = True
        return 1 if stale else 0
    for path, text in outputs:
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
