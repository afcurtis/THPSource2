#!/usr/bin/env python3
"""Writes src/launcher/thpsource2/core/upscale_tables.inc, the texture upscaler's shipped data compiled into the launcher (texture-upscaling plan T5):

  * the census recipe (re/config/texture_census.yml): one run a row, a session's keys already as OPENTONY_SESSION_KEYS (tony/session_scenarios.py KEYS);
  * the class table (re/config/texture_classes.tsv): one string a line, comments too (written back byte for byte: the upscaled set's stamp has its hash);
  * the download pins (re/config/upscaler.yml): the tool, every model, the person's pick (`chosen`).

    python scripts/make_upscale_tables.py [--check]

`--check` fails when the file on disk is not what this script writes (tests/test_upscale_tables.py runs it).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
OUT = ROOT / "src" / "launcher" / "thpsource2" / "core" / "upscale_tables.inc"


def c(text: str | None) -> str:
    if text is None:
        return "nullptr"
    return '"' + str(text).replace("\\", "\\\\").replace('"', '\\"') + '"'


def render() -> str:
    import yaml

    from tony.capture import SUPPORTED_BUILD_SHA256
    from tony.session_scenarios import KEYS

    recipe = yaml.safe_load((ROOT / "re" / "config" / "texture_census.yml").read_text())
    pins = yaml.safe_load((ROOT / "re" / "config" / "upscaler.yml").read_text())
    table_text = (ROOT / "re" / "config" / "texture_classes.tsv").read_bytes().decode("utf-8")
    if "\r" in table_text or not table_text.endswith("\n"):
        raise SystemExit("re/config/texture_classes.tsv: LF line ends and a final line end expected")
    table = table_text[:-1].split("\n")   # every line, comments too: the launcher writes the file back byte for byte (its hash is in the upscaled set's stamp)
    frames = recipe.get("frames", 600)
    unlock = (recipe.get("env") or {}).get("OT_UNLOCK", "")
    lines = [
        "// Generated by scripts/make_upscale_tables.py from re/config/texture_census.yml, re/config/texture_classes.tsv and re/config/upscaler.yml: do not edit.",
        "// Included by core/upscale_setup.cpp only.",
        "",
        f"constexpr const char* kCensusUnlock = {c(unlock)};",
        f"constexpr const char* kScenarioSha256 = {c(SUPPORTED_BUILD_SHA256)};   // a scenario file's build line (tony/capture.py)",
        "",
        "// name, psx textures, level (-1: a session from the boot), skater, look (-1: the scenario's), frames, actions (one a line), session keys, deliveries, unlock (nullptr: kCensusUnlock), undrawn 2d",
        "constexpr CensusRun kCensusRuns[] = {",
    ]
    for run in recipe["runs"]:
        session = "keys" in run
        keys = ",".join(f"{k['poll']}:{KEYS.get(k['key'], k['key']):x}:{k['hold']}" for k in run.get("keys", []))
        actions = "\\n".join(run.get("actions", []))
        lines.append(
            "    {" + ", ".join([
                c(run["name"]), "true" if run["textures"] == "psx" else "false", str(-1 if session else run["level"]), str(run.get("skater", -1)),
                str(run.get("look", -1)), str(run.get("frames", frames)), '"' + actions + '"', c(keys), str(run.get("deliveries", 0)),
                c(run["unlock"]) if "unlock" in run else "nullptr", "true" if session and run.get("undrawn", "2d") == "2d" else "false",
            ]) + "},")
    lines += ["};", ""]
    def download(tool: dict) -> str:
        return f"constexpr Download kTool = {{{c(tool['name'])}, {c(tool['url'])}, {tool['size']}u, {c(tool['sha256'])}, {c(tool['member'])}, {c(tool['licence'])}, {c(tool['source'])}}};"

    lines += [
        "// the tool: a zip whose `member` is the program",
        "#ifndef _WIN32",
        "// the Linux build of the same release (docs/LINUX.md)",
        download(pins["tool_linux"]),
        "#else",
        download(pins["tool"]),
        "#endif",
        "",
        "// every model the pins name: save_as, licence, author, the .param and the .bin",
        "constexpr ModelPin kModels[] = {",
    ]
    for model in pins["models"]:
        p, b = model["param"], model["bin"]
        lines.append(f"    {{{c(model['save_as'])}, {c(model['licence'])}, {c(model['author'])}, {{{c(p['url'])}, {p['size']}u, {c(p['sha256'])}}}, "
                     f"{{{c(b['url'])}, {b['size']}u, {c(b['sha256'])}}}}},")
    chosen = pins["chosen"]
    lines += [
        "};",
        "",
        f"constexpr const char* kChosenWorld = {c(chosen['world'])};",
        f"constexpr const char* kChosen2d = {c(chosen['2d'])};",
        f"constexpr int kChosenScale = {int(chosen['scale'])};",
        f"constexpr bool kChosenAlphaModel = {'true' if chosen['alpha'] == 'model' else 'false'};",
        "",
        f"// re/config/texture_classes.tsv, {len(table)} lines: written back joined by line ends, with one after the last",
        "constexpr const char* kClassRows[] = {",
    ]
    lines += [f"    {c(row)}," for row in table]
    lines += ["};", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is stale: run scripts/make_upscale_tables.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
