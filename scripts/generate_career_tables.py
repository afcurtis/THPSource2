#!/usr/bin/env python3
"""Generate src/runtime/career_tables.cpp from the canonical executable.

Usage: python scripts/generate_career_tables.py [--check]

The career, skater-manager and competition code read static tables the executable ships in
.data, at their retail addresses (RetailMemory regions):

  * the skater table: 20 rows of 0x170 bytes from 0x0053a3b8 (names, costume name pointers, face
    bitmap, unlock state, flags) plus the bytes either side the code reads, up to `levels`;
  * `levels` (0x0053c1f8): 13 records of 0x1ac bytes (name, contest flag, medal rewards, unlock
    requirements, gap range, the ten goal rows) and the text they point at, which follows them;
  * the pointer variable at 0x00537b84 (the face bitmap name of the alternate Tony Hawk costume).

`--check` exits non-zero when the checked-in file differs from what the executable produces.
"""

from __future__ import annotations

import struct
import sys
from pathlib import Path

import pefile

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from tony.hooks import _canonical_exe  # noqa: E402

OUTPUT = ROOT / "src" / "runtime" / "career_tables.cpp"

LEVELS_VA = 0x0053C1F8
LEVEL_COUNT = 13
LEVEL_STRIDE = 0x1AC
SKATERS_VA = 0x0053A3A4
FACE17_VA = 0x00537B84
# The competition judging table: 0x20-byte rows of three score thresholds (competition.cpp).
JUDGE_ROWS_VA = 0x005185D8
JUDGE_ROWS_SIZE = 0x200
# The 39 pointers to three-letter initials (and the initials, 4 bytes each, that follow them)
# Career_ResetSaveImage draws its default high-score names from.
NAMES_VA = 0x00524ED8
NAMES_SIZE = 0x140
# Pointer variables of the cheat list names (0x0052e3a4..0x0052e3ec) and "skip to restart".
CHEAT_NAMES_VA = 0x0052E3A4
CHEAT_NAMES_SIZE = 0x50
SKIP_NAME_VA = 0x0052E98C
CASH_TEXT_VA = 0x0052E2E8
CASH_STRING_VA = 0x00532E38   # "Cash Icons Cleared"
CASH_STRING_SIZE = 0x14
# The pointer variable Options_Init copies its default game name from, and that text ("HORSE").
HORSE_VA = 0x0052EA98
HORSE_TEXT_VA = 0x0053127C


def text_end(pe: pefile.PE, base: int, va: int) -> int | None:
    try:
        raw = pe.get_data(va - base, 96)
    except Exception:
        return None
    text = raw.split(b"\0", 1)[0]
    if not text or len(text) >= 96 or not all(0x20 <= b < 0x7F for b in text):
        return None
    return va + len(text) + 1


def c_bytes(data: bytes, per_line: int = 16) -> list[str]:
    return ["    " + ", ".join(f"0x{b:02x}" for b in data[i : i + per_line]) + "," for i in range(0, len(data), per_line)]


def regions(pe: pefile.PE) -> list[tuple[int, bytes]]:
    base = pe.OPTIONAL_HEADER.ImageBase
    levels = pe.get_data(LEVELS_VA - base, LEVEL_COUNT * LEVEL_STRIDE)
    end = LEVELS_VA + len(levels)
    for off in range(0, len(levels) - 3, 4):
        (value,) = struct.unpack_from("<I", levels, off)
        if 0x00530000 <= value < 0x00560000:
            stop = text_end(pe, base, value)
            if stop is not None:
                end = max(end, stop)
    return [
        (FACE17_VA, pe.get_data(FACE17_VA - base, 4)),
        (JUDGE_ROWS_VA, pe.get_data(JUDGE_ROWS_VA - base, JUDGE_ROWS_SIZE)),
        (NAMES_VA, pe.get_data(NAMES_VA - base, NAMES_SIZE)),
        (CHEAT_NAMES_VA, pe.get_data(CHEAT_NAMES_VA - base, CHEAT_NAMES_SIZE)),
        (SKIP_NAME_VA, pe.get_data(SKIP_NAME_VA - base, 4)),
        (CASH_TEXT_VA, pe.get_data(CASH_TEXT_VA - base, 4)),
        (CASH_STRING_VA, pe.get_data(CASH_STRING_VA - base, CASH_STRING_SIZE)),
        (HORSE_VA, pe.get_data(HORSE_VA - base, 4)),
        (HORSE_TEXT_VA, pe.get_data(HORSE_TEXT_VA - base, 8)),
        (SKATERS_VA, pe.get_data(SKATERS_VA - base, LEVELS_VA - SKATERS_VA)),
        (LEVELS_VA, pe.get_data(LEVELS_VA - base, end - LEVELS_VA)),
    ]


def render() -> str:
    pe = pefile.PE(str(_canonical_exe()))
    lines = [
        '#include "career_tables.hpp"',
        "",
        "// Generated by scripts/generate_career_tables.py from the canonical PC executable.",
        "// Do not edit; rerun the script.",
        "namespace opentony::runtime {",
        "namespace {",
        "",
    ]
    regs = regions(pe)
    for index, (va, data) in enumerate(regs):
        lines.append(f"// VA {va:#010x}, {len(data):#x} bytes")
        lines.append(f"constexpr std::uint8_t kRegion{index}[{len(data)}] = {{")
        lines += c_bytes(data)
        lines.append("};")
        lines.append("")
    lines += [
        "constexpr StaticRegion kRegions[] = {",
        *[f"    {{0x{va:08x}, kRegion{i}}}," for i, (va, _) in enumerate(regs)],
        "};",
        "",
        "}  // namespace",
        "",
        "std::span<const StaticRegion> career_static_regions() noexcept { return kRegions; }",
        "",
        "}  // namespace opentony::runtime",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = open(OUTPUT, newline="").read() if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT} is stale; rerun scripts/generate_career_tables.py", file=sys.stderr)
            return 1
        return 0
    with open(OUTPUT, "w", newline="") as handle:
        handle.write(text)
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
