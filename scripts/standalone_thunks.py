"""Write src/hooks/kits/standalone_thunks_generated.hpp: the retail executable's jump thunks (milestone 9).

usage: python scripts/standalone_thunks.py

A thunk is a function whose first instruction is `jmp rel32` (five bytes, then padding): the linker's incremental stubs and the compiler's tail stubs.
The scope map skips them (they are no function of their own) and the natives report a call to one by its address, so the standalone resolver, which
has no retail code to execute, needs to know where each one goes. This lists every thunk that a call instruction or a code pointer in the data
sections names, with its target, when the target is a function the knowledge base knows (functions.yml, the scope map or the native map); a byte
pattern that only looks like a call is thereby left out. Addresses only: nothing of the executable's code or data is copied.
"""

from __future__ import annotations

import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from tony import hooks  # noqa: E402
from tony.common import load_yaml  # noqa: E402

OUT = ROOT / "src/hooks/kits/standalone_thunks_generated.hpp"


def number(value) -> int:
    return int(value, 0) if isinstance(value, str) else int(value)


def main() -> int:
    raw = Path(hooks._canonical_exe()).read_bytes()
    lfanew = struct.unpack_from("<I", raw, 0x3C)[0]
    count = struct.unpack_from("<H", raw, lfanew + 6)[0]
    optional = struct.unpack_from("<H", raw, lfanew + 20)[0]
    sections = []
    for i in range(count):
        o = lfanew + 24 + optional + 40 * i
        vsize, rva, rawsize, rawptr = struct.unpack_from("<4I", raw, o + 8)
        flags = struct.unpack_from("<I", raw, o + 36)[0]
        sections.append((0x400000 + rva, min(vsize, rawsize), rawptr, flags & 0x20 != 0))
    text = next(s for s in sections if s[3])

    def byte(address: int) -> int | None:
        for va, size, rawptr, _ in sections:
            if va <= address < va + size:
                return raw[rawptr + address - va]
        return None

    def rel32(address: int) -> int:
        va, _, rawptr, _ = text
        return (address + 5 + struct.unpack_from("<i", raw, rawptr + address - va + 1)[0]) & 0xFFFFFFFF

    known: set[int] = set()
    known |= {number(row["address"]) for row in load_yaml("re/symbols/functions.yml")["functions"]}
    known |= {number(row["address"]) for row in load_yaml("re/native/functions.yml")["functions"] if row.get("address") is not None}
    known |= {number(row["address"]) for row in load_yaml("re/symbols/scope.yml")["functions"]}

    named: set[int] = set()
    va, size, rawptr, _ = text
    for offset in range(size - 5):
        if raw[rawptr + offset] == 0xE8:
            named.add(rel32(va + offset))
    for section_va, section_size, section_raw, is_code in sections:
        if is_code:
            continue
        for offset in range(0, section_size - 3, 4):
            word = struct.unpack_from("<I", raw, section_raw + offset)[0]
            if va <= word < va + size:
                named.add(word)

    thunks = []
    for address in sorted(named):
        if not va <= address < va + size - 5 or byte(address) != 0xE9 or address in known:
            continue
        target = rel32(address)
        if target in known:
            thunks.append((address, target))

    lines = [
        "// GENERATED by scripts/standalone_thunks.py from the canonical executable; do not edit by hand (milestone 9).",
        "//",
        "// The retail executable's jump thunks (a lone `jmp rel32`) that a call or a code pointer names, with their targets: the standalone resolver",
        "// (kit_dll.cpp) follows one to its target when the address itself is neither a native nor a seam.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace opentony::kitdll {",
        "",
        "struct Thunk {",
        "    std::uint32_t address;",
        "    std::uint32_t target;",
        "};",
        "",
        "// sorted by address",
        "inline constexpr Thunk kThunks[] = {",
    ]
    lines += [f"    {{0x{a:08x}, 0x{t:08x}}}," for a, t in thunks]
    lines += ["};", "", "}  // namespace opentony::kitdll", ""]
    OUT.write_text("\n".join(lines))
    print(f"{len(thunks)} thunks -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
