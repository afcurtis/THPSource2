#!/usr/bin/env python3
"""Generate src/runtime/trick_tip_table.cpp from the canonical executable.

Usage: python scripts/generate_trick_tip_table.py [--check]

The in-game trick tips (tricktips.cpp) live in a 22-entry table of five dwords at 0x00518b98:
an eligibility word, a second word, and three pointers to the text lines (0 = no line). The two
heading strings ("TIP:" and "REMEMBER:") are reached through pointer variables at 0x0052e290 and
0x0052e294. The retail code reads the pointers, so they are kept as the executable's own values
next to the text they name. `--check` exits non-zero when the checked-in file differs.
"""

from __future__ import annotations

import struct
import sys
from pathlib import Path

import pefile

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from tony.hooks import _canonical_exe  # noqa: E402

OUTPUT = ROOT / "src" / "runtime" / "trick_tip_table.cpp"
TABLE = 0x00518B98
ENTRIES = 22
TIP_TITLE = 0x0052E290
REMEMBER_TITLE = 0x0052E294


def cstring(pe: pefile.PE, va: int) -> str:
    base = pe.OPTIONAL_HEADER.ImageBase
    return pe.get_data(va - base, 64).split(b"\0", 1)[0].decode("latin-1")


def c_literal(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render() -> str:
    pe = pefile.PE(str(_canonical_exe()))
    base = pe.OPTIONAL_HEADER.ImageBase
    lines = [
        '#include "trick_tips.hpp"',
        "",
        "// Generated by scripts/generate_trick_tip_table.py from the canonical PC executable. Do not",
        "// edit; rerun the script. Pointers are the executable's own string addresses.",
        "namespace opentony::runtime {",
        "namespace {",
        "",
        f"// {ENTRIES} tips at VA {TABLE:#010x}: state word, second word, three line pointers.",
        f"constexpr std::array<TrickTipText, {ENTRIES}> kTipTextStorage{{{{",
    ]
    for i in range(ENTRIES):
        state, kind, p1, p2, p3 = struct.unpack("<5I", pe.get_data(TABLE - base + 20 * i, 20))
        texts = [cstring(pe, p) if p else "" for p in (p1, p2, p3)]
        lines.append(
            f"    TrickTipText{{0x{state:08x}U, 0x{kind:08x}U, {{0x{p1:08x}U, 0x{p2:08x}U, 0x{p3:08x}U}}, "
            f"{{{', '.join(c_literal(t) for t in texts)}}}}},"
        )
    tip_ptr = struct.unpack("<I", pe.get_data(TIP_TITLE - base, 4))[0]
    remember_ptr = struct.unpack("<I", pe.get_data(REMEMBER_TITLE - base, 4))[0]
    lines += [
        "}};",
        "",
        "} // namespace",
        "",
        "std::span<const TrickTipText> trick_tip_texts() noexcept { return kTipTextStorage; }",
        "",
        f"// 0x0052e290 -> {c_literal(cstring(pe, tip_ptr))}, 0x0052e294 -> {c_literal(cstring(pe, remember_ptr))}",
        f"std::uint32_t trick_tip_heading_pointer() noexcept {{ return 0x{tip_ptr:08x}U; }}",
        f"std::uint32_t trick_tip_remember_pointer() noexcept {{ return 0x{remember_ptr:08x}U; }}",
        "",
        "} // namespace opentony::runtime",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT} is out of date; run scripts/generate_trick_tip_table.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
