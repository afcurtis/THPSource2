#!/usr/bin/env python3
"""Generate src/trg/retail_gap_table.cpp from the canonical executable.

Usage: python scripts/generate_gap_tables.py [--check]

The three 0x2c-byte-record gap-definition tables are selected by
Front_LaunchGameLevel (0x004544a0). `--check` exits non-zero when the checked-in
file differs from what the executable produces.
"""

from __future__ import annotations

import struct
import sys
from pathlib import Path

import pefile

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from tony.hooks import _canonical_exe  # noqa: E402

OUTPUT = ROOT / "src" / "trg" / "retail_gap_table.cpp"
RECORD_SIZE = 0x2C

# (C++ enumerator, table VA, accessor comment)
TABLES = (
    ("EarlyLevels", 0x00541990),
    ("LateLevels", 0x00546110),
    ("CustomPark", 0x005283D0),
)


def read_table(pe: pefile.PE, va: int) -> list[tuple[int, int, int, int, bytes]]:
    base = pe.OPTIONAL_HEADER.ImageBase
    records = []
    while True:
        raw = pe.get_data(va - base + len(records) * RECORD_SIZE, RECORD_SIZE)
        flags, unknown, divider, score = struct.unpack_from("<HHHh", raw, 0)
        if divider == 0xFFFF:
            return records
        name = raw[8:].split(b"\0", 1)[0]
        if len(raw[8:].split(b"\0", 1)[0]) >= 36:
            raise SystemExit(f"gap record name is not NUL-terminated at {va:#x}")
        records.append((flags, divider, score, unknown, name))
        if len(records) > 4096:
            raise SystemExit(f"gap table at {va:#x} has no terminator")


def c_string(name: bytes) -> str:
    out = []
    for byte in name:
        char = chr(byte)
        if char == '"' or char == "\\":
            out.append("\\" + char)
        elif 0x20 <= byte < 0x7F and char != "?":
            out.append(char)
        else:
            out.append(f"\\{byte:03o}")
    return '"' + "".join(out) + '"'


def render() -> str:
    exe = _canonical_exe()
    pe = pefile.PE(str(exe))
    lines = [
        '#include "gap_table.hpp"',
        "",
        "// Generated by scripts/generate_gap_tables.py from the canonical PC",
        "// executable (0x2c-byte records, 0xffff divider terminator). Do not edit;",
        "// rerun the script. Which table a level uses is decided by",
        "// select_gap_table_variant() (Front_LaunchGameLevel, 0x004544a0).",
        "namespace opentony::trg {",
        "namespace {",
        "",
    ]
    for name, va in TABLES:
        records = read_table(pe, va)
        lines.append(f"// Table at VA {va:#010x}: {len(records)} records.")
        lines.append(f"GapTable make_{name}() {{")
        lines.append("    return GapTable::from_definitions({")
        for flags, divider, score, unknown, raw_name in records:
            lines.append(
                f"        TriggerGapDefinition{{0x{flags:04x}U, 0x{divider:04x}U, {score}, "
                f"{c_string(raw_name)}, 0x{unknown:04x}U}},"
            )
        lines.append("    });")
        lines.append("}")
        lines.append("")
    lines.append("} // namespace")
    lines.append("")
    lines.append("GapTableVariant select_gap_table_variant(int current_level, bool custom_park) noexcept {")
    lines.append("    if (custom_park) {")
    lines.append("        return GapTableVariant::CustomPark;")
    lines.append("    }")
    lines.append("    return current_level < 10 || current_level == 13")
    lines.append("        ? GapTableVariant::EarlyLevels")
    lines.append("        : GapTableVariant::LateLevels;")
    lines.append("}")
    lines.append("")
    lines.append("const GapTable& retail_gap_table(GapTableVariant variant) {")
    for name, _ in TABLES:
        lines.append(f"    static const GapTable {name[0].lower() + name[1:]} = make_{name}();")
    lines.append("    switch (variant) {")
    lines.append("    case GapTableVariant::EarlyLevels:")
    lines.append("        return earlyLevels;")
    lines.append("    case GapTableVariant::LateLevels:")
    lines.append("        return lateLevels;")
    lines.append("    case GapTableVariant::CustomPark:")
    lines.append("        return customPark;")
    lines.append("    }")
    lines.append("    return lateLevels;")
    lines.append("}")
    lines.append("")
    lines.append("const GapTable& retail_warehouse_gap_table() {")
    lines.append("    return retail_gap_table(GapTableVariant::LateLevels);")
    lines.append("}")
    lines.append("")
    lines.append("} // namespace opentony::trg")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT} is out of date; run scripts/generate_gap_tables.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
