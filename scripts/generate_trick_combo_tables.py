#!/usr/bin/env python3
"""Generate src/runtime/trick_combo_tables.cpp from the canonical executable.

Usage: python scripts/generate_trick_combo_tables.py [--check]

The trick database (trickdb.cpp) matches a trick's button list against two 12-byte-record
tables in the executable's data: the ordinary button combinations at 0x00540cb8 (terminated
by a zero count) and the special-trick combinations at 0x00540e30 (same shape, ends at a zero
count). Each record is six u16 words: count, three button codes, the trick-class mask and the
slot kind. `--check` exits non-zero when the checked-in file differs from the executable.
"""

from __future__ import annotations

import struct
import sys
from pathlib import Path

import pefile

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from tony.hooks import _canonical_exe  # noqa: E402

OUTPUT = ROOT / "src" / "runtime" / "trick_combo_tables.cpp"
RECORD_SIZE = 12

TABLES = (
    ("kBuiltInCombos", 0x00540CB8, "ordinary button combinations (FindButtonCombination, 0x004bc7e0)"),
    ("kSpecialCombos", 0x00540E30, "special-trick combinations (FindSpecialCombination, 0x004bc900)"),
)


def read_table(pe: pefile.PE, va: int) -> list[tuple[int, ...]]:
    base = pe.OPTIONAL_HEADER.ImageBase
    records = []
    while True:
        raw = pe.get_data(va - base + len(records) * RECORD_SIZE, RECORD_SIZE)
        words = struct.unpack("<6H", raw)
        if words[0] == 0:
            return records
        records.append(words)
        if len(records) > 256:
            raise SystemExit(f"combo table at {va:#x} has no terminator")


def render() -> str:
    pe = pefile.PE(str(_canonical_exe()))
    lines = [
        '#include "trick_database.hpp"',
        "",
        "// Generated by scripts/generate_trick_combo_tables.py from the canonical PC",
        "// executable. Do not edit; rerun the script. Records are the executable's own six",
        "// words: count, three button codes, class mask, slot kind.",
        "namespace opentony::runtime {",
        "namespace {",
        "",
    ]
    for name, va, comment in TABLES:
        records = read_table(pe, va)
        lines.append(f"// {comment}: table at VA {va:#010x}, {len(records)} records.")
        lines.append(f"constexpr std::array<ComboWords, {len(records)}> {name}Storage{{{{")
        for words in records:
            lines.append("    ComboWords{" + ", ".join(f"0x{w:04x}U" for w in words) + "},")
        lines.append("}};")
        lines.append("")
    lines.append("} // namespace")
    lines.append("")
    lines.append("std::span<const ComboWords> builtin_combos() noexcept { return kBuiltInCombosStorage; }")
    lines.append("std::span<const ComboWords> special_combos() noexcept { return kSpecialCombosStorage; }")
    lines.append("")
    lines.append("} // namespace opentony::runtime")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT} is out of date; run scripts/generate_trick_combo_tables.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
